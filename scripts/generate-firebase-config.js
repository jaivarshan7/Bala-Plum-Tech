#!/usr/bin/env node

/**
 * scripts/generate-firebase-config.js
 *
 * Generates the client-side `js/firebase/firebase-config.js` file from environment
 * variables (e.g. GitHub Actions secrets in CI) or a local `.env` file for local development.
 *
 * Usage:
 *   node scripts/generate-firebase-config.js                 # Uses env vars or .env
 *   node scripts/generate-firebase-config.js --placeholder   # Generates template with placeholders
 *   node scripts/generate-firebase-config.js --output <path> # Custom output path
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

// Simple zero-dependency .env parser
function loadEnvFile(envPath) {
  const env = {};
  if (!fs.existsSync(envPath)) return env;

  const content = fs.readFileSync(envPath, 'utf8');
  const lines = content.split(/\r?\n/);

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;

    const eqIndex = trimmed.indexOf('=');
    if (eqIndex === -1) continue;

    const key = trimmed.slice(0, eqIndex).trim();
    let val = trimmed.slice(eqIndex + 1).trim();

    // Strip wrapping quotes
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }

    env[key] = val;
  }
  return env;
}

let isPlaceholder = false;
let outputPath = path.join(projectRoot, 'js', 'firebase', 'firebase-config.js');
let envFilePath = path.join(projectRoot, '.env');
const args = process.argv.slice(2);

for (let i = 0; i < args.length; i++) {
  if (args[i] === '--placeholder' || args[i] === '--allow-placeholders') {
    isPlaceholder = true;
  } else if (args[i] === '--output' && args[i + 1]) {
    outputPath = path.resolve(projectRoot, args[i + 1]);
    i++;
  } else if (args[i] === '--env-file' && args[i + 1]) {
    envFilePath = path.resolve(projectRoot, args[i + 1]);
    i++;
  }
}

// Merge sources: process.env > .env file
const localEnv = loadEnvFile(envFilePath);

function getVal(key, fallbackKey) {
  return (
    process.env[key] ||
    (fallbackKey ? process.env[fallbackKey] : undefined) ||
    localEnv[key] ||
    (fallbackKey ? localEnv[fallbackKey] : undefined) ||
    ''
  );
}

const config = {
  apiKey: isPlaceholder ? 'YOUR_API_KEY' : getVal('FIREBASE_API_KEY'),
  authDomain: isPlaceholder ? 'YOUR_AUTH_DOMAIN' : getVal('FIREBASE_AUTH_DOMAIN'),
  projectId: isPlaceholder ? 'YOUR_PROJECT_ID' : getVal('FIREBASE_PROJECT_ID'),
  storageBucket: isPlaceholder ? 'YOUR_STORAGE_BUCKET' : getVal('FIREBASE_STORAGE_BUCKET', 'FIREBASE_STORAGEBUCKET'),
  messagingSenderId: isPlaceholder ? 'YOUR_MESSAGING_SENDER_ID' : getVal('FIREBASE_MESSAGING_SENDER_ID'),
  appId: isPlaceholder ? 'YOUR_APP_ID' : getVal('FIREBASE_APP_ID'),
  measurementId: isPlaceholder ? 'YOUR_MEASUREMENT_ID' : getVal('FIREBASE_MEASUREMENT_ID')
};

// Check for missing required values in non-placeholder mode
const requiredKeys = ['apiKey', 'authDomain', 'projectId', 'messagingSenderId', 'appId'];
const envKeyMap = {
  apiKey: 'FIREBASE_API_KEY',
  authDomain: 'FIREBASE_AUTH_DOMAIN',
  projectId: 'FIREBASE_PROJECT_ID',
  messagingSenderId: 'FIREBASE_MESSAGING_SENDER_ID',
  appId: 'FIREBASE_APP_ID'
};

const missing = requiredKeys.filter((k) => !config[k] || config[k].trim() === '');

if (!isPlaceholder && missing.length > 0) {
  const missingEnvNames = missing.map((k) => envKeyMap[k]).join(', ');
  console.error(`\n[ERROR] Missing required Firebase configuration values: ${missingEnvNames}`);
  console.error('Please set these environment variables or define them in your local .env file.');
  console.error('To generate a template with placeholders, run: node scripts/generate-firebase-config.js --placeholder\n');
  process.exit(1);
}

// Format config object cleanly
const configEntries = [
  `  apiKey: ${JSON.stringify(config.apiKey)},`,
  `  authDomain: ${JSON.stringify(config.authDomain)},`,
  `  projectId: ${JSON.stringify(config.projectId)},`
];

if (config.storageBucket) {
  configEntries.push(`  storageBucket: ${JSON.stringify(config.storageBucket)},`);
}
configEntries.push(`  messagingSenderId: ${JSON.stringify(config.messagingSenderId)},`);
configEntries.push(`  appId: ${JSON.stringify(config.appId)},`);

if (config.measurementId) {
  configEntries.push(`  measurementId: ${JSON.stringify(config.measurementId)},`);
}

// Format the final file content
const fileContent = `/**
 * Auto-generated Firebase Web Client Configuration.
 * DO NOT EDIT DIRECTLY OR COMMIT TO VERSION CONTROL.
 *
 * Generated by scripts/generate-firebase-config.js
 * Source: ${isPlaceholder ? 'Placeholder template' : (process.env.CI ? 'CI Environment Secrets' : 'Environment Variables / .env')}
 */

const firebaseConfig = {
${configEntries.join('\n')}
};

const hasConfiguredFirebase = !Object.values(firebaseConfig).some((value) => typeof value === 'string' && value.includes('YOUR_'));

export function getFirebaseConfig() {
  return { ...firebaseConfig };
}

export function initializeFirebase() {
  if (!window.firebase) {
    console.warn('Firebase SDK has not loaded yet. Add your Firebase project credentials to firebase-config.js before running the app.');
    return { app: null, auth: null, db: null };
  }

  if (!hasConfiguredFirebase) {
    console.warn('Firebase client config is still using placeholder values. Update js/firebase/firebase-config.js before using the app with real data.');
    return { app: null, auth: null, db: null };
  }

  if (!window.firebase.apps.length) {
    window.firebase.initializeApp(firebaseConfig);
  }

  const firebaseApp = window.firebase.app();
  const firebaseAuth = window.firebase.auth();
  const firestore = window.firebase.firestore();

  if (!window.__plumbtrackPersistenceInitialized && firestore?.enablePersistence) {
    window.__plumbtrackPersistenceInitialized = true;
    firestore.enablePersistence({ synchronizeTabs: true }).catch((err) => {
      // Multiple tabs open or private browsing mode - silently fall back to normal mode
      if (err.code !== 'failed-precondition' && err.code !== 'unimplemented') {
        console.warn('Firestore offline persistence notice:', err.message);
      }
    });
  }

  Object.assign(window, {
    __plumbtrackApp: firebaseApp,
    __plumbtrackAuth: firebaseAuth,
    __plumbtrackDb: firestore,
    db: firestore,
    auth: firebaseAuth
  });

  return {
    app: firebaseApp,
    auth: firebaseAuth,
    db: firestore
  };
}

export function getFirebaseServices() {
  if (!window.__plumbtrackApp) {
    return initializeFirebase();
  }

  return {
    app: window.__plumbtrackApp,
    auth: window.__plumbtrackAuth,
    db: window.__plumbtrackDb
  };
}

export const app = null;
export const auth = null;
export const db = null;
`;

// Ensure target directory exists and write file
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, fileContent, 'utf8');

const relPath = path.relative(projectRoot, outputPath);
console.log(`[SUCCESS] Generated Firebase configuration at: ${relPath} (${isPlaceholder ? 'placeholder mode' : 'configured mode'})`);
